/**
 * Builds src/lib/reports/design/fonts.generated.ts: Inter and Source Serif 4
 * as base64 @font-face rules, so a report needs no network for its type, on
 * screen or in Chromium's PDF. Run it again only when the fonts change:
 *
 *   npx tsx src/scripts/build-report-fonts.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const FACES = [
  { family: 'Inter', pkg: 'inter', weights: [400, 500, 600, 700] },
  { family: 'Source Serif 4', pkg: 'source-serif-4', weights: [600, 700] },
];

const root = join(__dirname, '..', '..');
const rules: string[] = [];
let bytes = 0;

for (const face of FACES) {
  for (const weight of face.weights) {
    const file = join(
      root,
      'node_modules',
      '@fontsource',
      face.pkg,
      'files',
      `${face.pkg}-latin-${weight}-normal.woff2`
    );
    const font = readFileSync(file);
    bytes += font.length;
    rules.push(
      `@font-face { font-family: "${face.family}"; font-style: normal; font-weight: ${weight}; font-display: swap; src: url(data:font/woff2;base64,${font.toString('base64')}) format("woff2"); }`
    );
  }
}

const out = join(root, 'src', 'lib', 'reports', 'design', 'fonts.generated.ts');
writeFileSync(
  out,
  `// Generated by src/scripts/build-report-fonts.ts from the @fontsource packages.
// Do not edit. Inter and Source Serif 4, Latin subset, SIL Open Font License 1.1.
// prettier-ignore
export const FONT_FACES = ${JSON.stringify(rules.join('\n'))};
`
);
console.log(`Wrote ${rules.length} faces, ${Math.round(bytes / 1024)} KB of fonts, to ${out}`);
